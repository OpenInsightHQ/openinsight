#!/bin/bash
#============================================================
# OpenInsight 环境初始化脚本
#
# 功能：从 env.sh.example 生成 env.sh，自动填充所有随机密钥/密码
#
# 用法：bash init-env.sh
#============================================================

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"

source "${SCRIPT_DIR}/common.sh"

echo "============================================================"
echo "       OpenInsight 环境初始化"
echo "============================================================"
echo ""

ensure_env

echo ""
echo "============================================================"
echo "       环境初始化完成!"
echo "============================================================"
echo ""
echo "env.sh 已生成，所有密钥/密码已随机填充。"
echo ""
echo "下一步："
echo "  1. 编辑 env.sh，修改 HOST_IP 为实际服务器 IP"
echo "  2. 如需自定义其他配置（端口、外部中间件等），在 env.sh 中修改"
echo "  3. 运行 bash install_all.sh 开始安装"
echo ""
